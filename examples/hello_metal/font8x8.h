// Index helper: returns the glyph index for `ch`, or 0 (space) if unsupported.
[[nodiscard]] constexpr std::uint8_t glyph_index(char ch) noexcept {
    if (ch >= '0' && ch <= '9') return static_cast<std::uint8_t>(1 + (ch - '0'));   // 1..10
    if (ch >= 'A' && ch <= 'Z') return static_cast<std::uint8_t>(11 + (ch - 'A'));  // 11..36
    if (ch >= 'a' && ch <= 'z') return static_cast<std::uint8_t>(11 + (ch - 'a'));  // map lower -> upper
    switch (ch) {
        case ' ':  return 0;
        case '.':  return 37;
        case ':':  return 38;
        case '-':  return 39;
        case '/':  return 40;
        case '|':  return 41;
        case '(':  return 42;
        case ')':  return 43;
        case '[':  return 44;
        case ']':  return 45;
        case '%':  return 46;
        case '=':  return 47;
        case '+':  return 48;
        case ',':  return 49;
        case '<':  return 50;
        case '>':  return 51;
        default:   return 0;
    }
}

